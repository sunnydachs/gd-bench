"""bench — 検出した箇所に対応する Godot マイクロベンチを生成する（決定論的）。

生成物は実行可能な GDScript（extends SceneTree、_init で完結、エディタ不要）。
ベンチ対象の型（untyped/typed/packed/dict）ごとに、同じ操作（append N 件 + 反復合計）を
2 つのデータ構造で測り、経過時間（usec）を出力する。

生成されたベンチは Godot 4 の headless で走る:
  godot --headless --script bench_gd_xxxx.gd
"""
from datetime import datetime, timezone

# ベンチ対象: (label_a, label_b) — ラベルは _pair_key で bodies 辞書キーに解決される
BENCH_PAIRS = {
    "untyped_array": ("Array (untyped)", "Array[T] (typed)"),
    "typed_array": ("Array[T] (typed)", "PackedInt32Array"),
    "dict_as_array": ("Dictionary (indexed)", "Array (untyped)"),
}

# bodies 辞書キー → GDScript 関数名（A/B どちらのスロットに入るかで決まる）
FUNC_SLOT = {"untyped_array": ("_bench_a", "_bench_b"),
             "typed_array": ("_bench_a", "_bench_b"),
             "dict_as_array": ("_bench_a", "_bench_b"),
             "packed_array": ("_bench_a", "_bench_b")}

BENCH_TEMPLATE = """# Auto-generated by gd-bench v0.1.0 — {ts}
# bench target: {focus}  ({note})
# usage: godot --headless --script {name}
extends SceneTree

const N := {n}


func _init() -> void:
\t# {label_a} vs {label_b} - append + iterate-sum, N elements
\tvar usec_a := _bench_a()
\tvar usec_b := _bench_b()
\tprint("gd-bench: {focus}")
\tprint("  {label_a}: %d usec" % usec_a)
\tprint("  {label_b}: %d usec" % usec_b)
\tif usec_a > 0 and usec_b > 0:
\t\tvar ratio := float(usec_a) / float(usec_b)
\t\tprint("  ratio: %.2fx" % ratio)
\tquit(0)
"""


def bench_name(focus: str, line_no: int) -> str:
    """決定論的なベンチファイル名（focus + 行番号）。"""
    safe = "".join(c if c.isalnum() else "_" for c in focus)[:40]
    return f"bench_gd_{safe}_{line_no}.gd"


def render_bench(kind_a: str, kind_b: str, focus: str, note: str,
                 n: int = 100_000, ts: str | None = None) -> str:
    """2 構造比較マイクロベンチの GDScript を返す（決定論的）。

    kind_a/kind_b は bodies 辞書のキー（"untyped_array" 等）。
    関数名は A スロット/ B スロットで衝突しないよう _bench_a / _bench_b に再マップする。
    """
    ts = ts or datetime.now(timezone.utc).isoformat()
    name = bench_name(focus, 0)
    header = BENCH_TEMPLATE.format(
        ts=ts, focus=focus, note=note, name=name, n=n,
        label_a=kind_a, label_b=kind_b,
    )
    bodies = {"untyped_array": _body_untyped, "typed_array": _body_typed,
              "dict_as_array": _body_dict, "packed_array": _body_packed}
    if kind_a not in bodies or kind_b not in bodies:
        raise KeyError(f"unknown bench kind: {kind_a} / {kind_b}")
    a = bodies[kind_a](n).replace(_slot_of(kind_a), "_bench_a", 1)
    b = bodies[kind_b](n).replace(_slot_of(kind_b), "_bench_b", 1)
    return header + "\n" + a + "\n\n" + b + "\n"


def _slot_of(kind: str) -> str:
    """その kind の body に書かれている元の関数名（先頭の def 名）。"""
    bodies = {"untyped_array": "_bench_a", "typed_array": "_bench_b",
              "dict_as_array": "_bench_a", "packed_array": "_bench_b"}
    return bodies[kind]


def _body_untyped(n: int) -> str:
    return f"""func _bench_a() -> int:
\tvar t0 := Time.get_ticks_usec()
\tvar arr := []
\tfor i in range({n}):
\t\tarr.append(i)
\tvar total := 0
\tfor v in arr:
\t\ttotal += v
\treturn Time.get_ticks_usec() - t0"""


def _body_typed(n: int) -> str:
    return f"""func _bench_b() -> int:
\tvar t0 := Time.get_ticks_usec()
\tvar arr: Array[int] = []
\tfor i in range({n}):
\t\tarr.append(i)
\tvar total := 0
\tfor v in arr:
\t\ttotal += v
\treturn Time.get_ticks_usec() - t0"""


def _body_dict(n: int) -> str:
    return f"""func _bench_a() -> int:
\tvar t0 := Time.get_ticks_usec()
\tvar d := {{}}
\tfor i in range({n}):
\t\td[i] = i
\tvar total := 0
\tfor i in range({n}):
\t\ttotal += d[i]
\treturn Time.get_ticks_usec() - t0"""


def _body_packed(n: int) -> str:
    return f"""func _bench_b() -> int:
\tvar t0 := Time.get_ticks_usec()
\tvar arr: PackedInt32Array = []
\tfor i in range({n}):
\t\tarr.append(i)
\tvar total := 0
\tfor v in arr:
\t\ttotal += v
\treturn Time.get_ticks_usec() - t0"""


def bench_for_finding(f: dict, n: int = 100_000, ts: str | None = None) -> str:
    """検出 1 件に対応するベンチ GDScript を返す。

    f: scan の findings 要素（kind, snippet, ...）。
    """
    kind = f["kind"]
    if kind == "packed_array":
        # Packed は既に最適 — 対応する比較ベンチは無い（正の指摘のみ）
        return ""
    pair = BENCH_PAIRS[kind]
    # kind_a/kind_b は bodies 辞書のキー（"untyped_array" 等）をそのまま渡す
    return render_bench(_pair_key(pair[0]), _pair_key(pair[1]),
                        kind, f.get("note", ""), n=n, ts=ts)


def _pair_key(label: str) -> str:
    """ベンチラベル（"Array (untyped)" 等）→ bodies 辞書キー。"""
    if "untyped" in label:
        return "untyped_array"
    if "Packed" in label:
        return "packed_array"
    if "Dictionary" in label:
        return "dict_as_array"
    if "typed" in label and "Array" in label:
        return "typed_array"
    if label.strip() == "Array":
        return "untyped_array"   # 型ヒント無しの素の Array
    raise KeyError(label)
